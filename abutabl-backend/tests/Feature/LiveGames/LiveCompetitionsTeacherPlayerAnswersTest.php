    public function test_owning_teacher_can_review_player_answers(): void
    {
        $playing = $this->openPlaying([21, 22]);
        $snapshot = LiveGameSessionQuestion::query()
            ->where('live_game_session_id', $playing['id'])
            ->orderBy('id')
            ->first();

        LiveGameSessionAnswer::create([
            'live_game_session_id' => $playing['id'],
            'student_id' => 21,
            'live_game_session_question_id' => $snapshot->id,
            'answer' => 'Sun',
            'correct' => false,
            'coins_delta' => 0,
            'elapsed_ms' => 1500,
            'timed_out' => false,
            'is_retry' => false,
            'is_reinforce' => false,
            'attempt' => 1,
        ]);
        LiveGameSessionAnswer::create([
            'live_game_session_id' => $playing['id'],
            'student_id' => 21,
            'live_game_session_question_id' => $snapshot->id,
            'answer' => 'Wood',
            'correct' => true,
            'coins_delta' => 3,
            'elapsed_ms' => 900,
            'timed_out' => false,
            'is_retry' => true,
            'is_reinforce' => false,
            'attempt' => 2,
        ]);
        LiveGameSessionPlayer::query()->where('student_id', 21)->update([
            'score' => 1,
            'coins' => 30,
        ]);

        $this->actingTeacher(10);
        $response = $this->playerAnswers($playing['id'], 21);
        $payload = $response->getData(true);

        $this->assertSame(200, $response->getStatusCode());
        $this->assertTrue($payload['status']);
        $review = $payload['review'];
        $this->assertSame((int) $playing['id'], $review['session']['id']);
        $this->assertSame(21, $review['student']['id']);
        $this->assertSame('Student 21', $review['student']['name']);
        $this->assertSame(1, (int) $review['player']['score']);
        $this->assertSame(1, (int) $review['player']['rank']);
        $this->assertNotEmpty($review['questions']);
        $first = $review['questions'][0];
        $this->assertSame((int) $snapshot->id, $first['id']);
        $this->assertSame('Wood', $first['correct_answer']);
        $this->assertTrue($first['answered']);
        $this->assertTrue($first['ever_correct']);
        $this->assertCount(2, $first['attempts']);
        $this->assertFalse($first['attempts'][0]['correct']);
        $this->assertSame('Sun', $first['attempts'][0]['answer']);
        $this->assertTrue($first['attempts'][1]['correct']);
        $this->assertTrue($first['attempts'][1]['is_retry']);
    }

    public function test_non_owner_cannot_review_player_answers(): void
    {
        $playing = $this->openPlaying([21]);
        $other = $this->actingTeacher(11);
        $this->assignClass($other->id, 1, 5);

        $response = $this->playerAnswers($playing['id'], 21);
        $this->assertSame(403, $response->getStatusCode());
    }

    public function test_missing_player_is_not_found(): void
    {
        $playing = $this->openPlaying([21]);
        $this->actingTeacher(10);

        $response = $this->playerAnswers($playing['id'], 999);
        $this->assertSame(404, $response->getStatusCode());
    }

    public function test_review_lists_unanswered_questions(): void
    {
        $playing = $this->openPlaying([21]);
        $this->actingTeacher(10);

        $response = $this->playerAnswers($playing['id'], 21);
        $payload = $response->getData(true);
        $this->assertSame(200, $response->getStatusCode());
        $first = $payload['review']['questions'][0];
        $this->assertFalse($first['answered']);
        $this->assertFalse($first['ever_correct']);
        $this->assertSame([], $first['attempts']);
        $this->assertArrayHasKey('correct_answer', $first);
    }

    public function test_route_is_flagged_teacher(): void
    {
        $uri = 'api/live-competitions/sessions/{id}/players/{studentId}/answers';
        $route = collect(Route::getRoutes())->first(function ($route) use ($uri) {
            return $route->uri() === $uri && in_array('GET', $route->methods(), true);
        });
        $this->assertNotNull($route);
        $middleware = $route->gatherMiddleware();
        $this->assertContains('ensureLiveCompetitionsEnabled', $middleware);
        $this->assertContains('checkUserToken:admin-api', $middleware);
        $this->assertNotContains('ensureLiveCompetitionsAdminOnly', $middleware);
    }

    public function test_review_source_has_no_writes(): void
    {
        $source = file_get_contents(app_path(
            'Support/LiveCompetitions/LiveCompetitionSessionService.php'
        ));
        $body = $this->methodBody($source, 'getPlayerAnswersReview');
        $this->assertFalse(str_contains($body, 'lockForUpdate'));
        $this->assertFalse(str_contains($body, '->update('));
        $this->assertFalse(str_contains($body, '->save('));
        $this->assertFalse(str_contains($body, '->create('));
        $this->assertFalse(str_contains($body, '->delete('));
    }

    private function playerAnswers($sessionId, $studentId)
    {
        return $this->app->make(LiveCompetitionsTeacherController::class)
            ->playerAnswers($sessionId, $studentId);
    }

    /**
     * @param  int[]  $joinStudentIds
     * @return array<string,mixed>
     */
    private function openPlaying(array $joinStudentIds): array
    {
        $lobby = $this->openLobbyWithStudents($joinStudentIds);
        $this->joinStudents($lobby['id'], $joinStudentIds);
        $this->actingTeacher(10);
        $this->app->make(LiveCompetitionSessionService::class)
            ->beginLobbySession(10, (int) $lobby['id']);

        return LiveGameSession::query()->find($lobby['id'])->toArray();
    }

    /**
     * @param  int[]  $studentIds
     * @return array<string,mixed>
     */
    private function openLobbyWithStudents(array $studentIds): array
    {
        $teacher = $this->actingTeacher(10);
        $this->assignClass($teacher->id, 1, 5);
        foreach ($studentIds as $id) {
            $this->insertStudent($id, 1, 5, '1', 'Student '.$id);
        }
        $game = $this->publishedEntitledGame(5);

        return $this->app->make(LiveCompetitionSessionService::class)
            ->createLobbySession($teacher->id, $game->id, 1, [5]);
    }

    /**
     * @param  int[]  $studentIds
     */
    private function joinStudents($sessionId, array $studentIds): void
    {
        $service = $this->app->make(LiveCompetitionSessionService::class);
        foreach ($studentIds as $studentId) {
            $service->joinLobbySession((int) $studentId, (int) $sessionId);
        }
    }

    private function actingTeacher(int $id): User
    {
        $existing = User::query()->find($id);
        $teacher = $existing ?: User::create([
            'id' => $id,
            'type' => 'teacher',
            'name' => 'Teacher '.$id,
            'school_id' => 5,
        ]);
        $this->app['auth']->shouldUse('admin-api');
        $this->app['auth']->guard('admin-api')->setUser($teacher);

        return $teacher;
    }

    private function assignClass(int $teacherId, int $classId, int $schoolId): void
    {
        if (! Classes::query()->where('id', $classId)->exists()) {
            Classes::create(['id' => $classId, 'school_id' => $schoolId, 'name' => 'Class '.$classId]);
        }
        if (! TeachersGrades::query()->where('user_id', $teacherId)->where('class_id', $classId)->exists()) {
            TeachersGrades::create([
                'user_id' => $teacherId,
                'school_id' => $schoolId,
                'class_id' => $classId,
                'grade_id' => 1,
                'subject_id' => 1,
                'status' => 1,
            ]);
        }
        if (! SchoolsRoles::query()->where('user_id', $teacherId)->where('school_id', $schoolId)->exists()) {
            SchoolsRoles::create([
                'user_id' => $teacherId,
                'school_id' => $schoolId,
                'role_id' => 1,
                'status' => 1,
            ]);
        }
    }

    private function publishedEntitledGame(int $schoolId): LiveGame
